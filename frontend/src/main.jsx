import React, { useState } from 'react';
import { createRoot } from 'react-dom/client';
import 'leaflet/dist/leaflet.css';
import './styles.css';
import Dashboard from './pages/Dashboard';
import { request } from './services/api';

function App() {
  const [auth, setAuth] = useState(null), [error, setError] = useState(''), [busy, setBusy] = useState(false);
  async function login(event) {
    event.preventDefault(); setBusy(true); setError('');
    const form = new FormData(event.target), value = {organization: form.get('organization').trim(), token: form.get('token').trim()};
    try {await request('/assets', value); setAuth(value);} catch(e) {setError(e.message);} finally {setBusy(false);}
  }
  return auth ? <Dashboard auth={auth} logout={() => setAuth(null)}/> : <main className="login"><div className="brand">◈ MERIDIAN</div><p className="eyebrow">FLEET INTELLIGENCE / LOCAL DEMO</p><h1>A clearer view<br/>of every journey.</h1><p className="muted">Sign in to your organization’s tracking workspace.</p><form onSubmit={login}><label>Organization<input name="organization" defaultValue="demo" required autoComplete="organization"/></label><label>Operator token<input name="token" type="password" required autoComplete="off"/></label>{error && <p role="alert" className="error">{error}</p>}<button className="primary" disabled={busy}>{busy ? 'Connecting…' : 'Open workspace →'}</button></form><p className="muted">Use the operator token generated by the demo seed command.<br/>Credentials stay in memory until you sign out or reload.</p></main>;
}
createRoot(document.getElementById('root')).render(<App/>);
